test('rejects invalid metadata, header injection, unsafe links, and permission or license overrides', () => {
  const invalid = [
    null,
    [],
    'text',
    new Date(),
    {description: ''},
    {description: ' padded '},
    {author: {name: 'Someone'}},
    {authorURL: 'https://example.com/'},
    {author: 'A', authorURL: 'javascript:alert(1)'},
    {author: 'A', authorURL: 'https://user:secret@example.com/'},
    {docsURL: 'http://example.com/'},
    {repository: 'ftp://example.com/'},
    {description: 'x\n// Unsandboxed: not-needed'},
    {description: 'x\u2028// By: Elsewhere'},
    {version: 'x'.repeat(1001)},
    {descriptions: []},
    {descriptions: {JA: 'text'}},
    {descriptions: {ja_jp: 'text'}},
    {descriptions: {ja: ''}},
    {package: '../other'},
    {package: 'node_modules'},
    {package: 'favicon.ico'},
    {package: '@Example/App'},
    {unsandboxed: 'not-needed'},
    {license: 'MIT'},
    {id: 'other'},
    {name: 'other'},
    {banner: 'data:text/html,<script>alert(1)</script>'},
    {banner: 'data:image/svg+xml,'},
    {banner: 'data:image/png;base64,??'},
    {banner: 'data:image/svg+xml,%xx'},
  ];
  for (const value of invalid) {
    expect(() =>
      validateExtensionBundleConfigurations(
        [{...bundle, metadata: value}],
        components.map((x) => x.extension),
      ),
    ).toThrow();
  }
});

test('allows explicit HTTPS banners and supported image data URLs', () => {
  for (const value of [
    banner,
    'https://example.com/banner.png',
    'data:image/png;base64,AA==',
    'data:image/jpeg;base64,AA==',
    'data:image/gif;base64,AA==',
    'data:image/webp;base64,AA==',
  ]) {
    expect(
      validateExtensionBundleConfigurations(
        [{...bundle, metadata: {banner: value}}],
        components.map((x) => x.extension),
      )[0].metadata?.banner,
    ).toBe(value);
  }
  expect(
    validateExtensionBundleConfigurations(
      [{...bundle, metadata: {banner: banner.replace('data:image/svg+xml', 'DATA:IMAGE/SVG+XML')}}],
      components.map((x) => x.extension),
    )[0].metadata?.banner,
  ).toBe(banner);
});


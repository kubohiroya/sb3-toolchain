async function classicFixture() {
  const root = await mkdtemp(path.join(os.tmpdir(), 'sb3-bundle-metadata-'));
  const sourceDirectory = path.join(root, 'app');
  await cp(new URL('./fixtures/minimal-source/', import.meta.url), sourceDirectory, {
    recursive: true,
  });
  await rm(path.join(sourceDirectory, 'extensions/example.js'));
  for (const component of components)
    await writeFile(path.join(sourceDirectory, component.extension.path), component.contents);
  const project = JSON.parse(
    await readFile(path.join(sourceDirectory, 'project.source.json'), 'utf8'),
  );
  project.extensions = [...bundle.members];
  project.extensionURLs = Object.fromEntries(
    components.map((c) => [c.extension.id, `embedded-extension:${c.extension.path}`]),
  );
  for (const target of project.targets) target.blocks = {};
  await writeFile(path.join(sourceDirectory, 'project.source.json'), JSON.stringify(project));
  const manifestPath = path.join(sourceDirectory, 'embedded-extensions.json');
  await writeFile(
    manifestPath,
    JSON.stringify({formatVersion: 1, extensions: components.map((c) => c.extension)}),
  );
  return {root, sourceDirectory, manifestPath};
}

test('retains metadata in plan, transactional apply, source inspection, and CLI configuration', async () => {
  const f = await classicFixture();
  try {
    const input = {
      bundleId: bundle.id,
      bundleName: bundle.name,
      metadata,
      sourceDirectory: f.sourceDirectory,
    };
    const before = await readFile(f.manifestPath);
    expect((await planExtensionBundle(input)).metadata).toEqual(metadata);
    expect(await readFile(f.manifestPath)).toEqual(before);
    expect((await bundleExtensions({...input, yes: true})).metadata).toEqual(metadata);
    expect(JSON.parse(await readFile(f.manifestPath, 'utf8')).extensionBundles[0].metadata).toEqual(
      metadata,
    );
    const built = await createDeterministicSb3(f.sourceDirectory);
    const project = JSON.parse(strFromU8(unzipSync(built.archive)['project.json']));
    const encoded = project.extensionURLs.projectbundle as string;
    const header = topHeader(Buffer.from(encoded.slice(encoded.indexOf(',') + 1), 'base64'));
    expect(header).toContain('// Package: @example/application\n');
    expect(header).toContain(`// Banner: ${banner}\n`);
    expect(built.bundlePlans[0].bundle.metadata).toEqual(metadata);
    await unbundleExtensions({bundleId: bundle.id, sourceDirectory: f.sourceDirectory, yes: true});
    await runCli(
      [
        'extensions',
        'bundle',
        f.sourceDirectory,
        '--id',
        bundle.id,
        '--name',
        bundle.name,
        '--metadata-json',
        JSON.stringify(metadata),
        '--yes',
      ],
      {log: () => {}},
    );
    expect(JSON.parse(await readFile(f.manifestPath, 'utf8')).extensionBundles[0].metadata).toEqual(
      metadata,
    );
    expect((await createDeterministicSb3(f.sourceDirectory)).archive).toEqual(built.archive);
    for (const component of components)
      expect(await readFile(path.join(f.sourceDirectory, component.extension.path), 'utf8')).toBe(
        component.contents,
      );
  } finally {
    await rm(f.root, {recursive: true, force: true});
  }
});

test('validates CLI JSON before configuring or writing the source', () => {
  const args = ['extensions', 'bundle', 'app', '--id', bundle.id, '--name', bundle.name];
  expect(parseCliArguments([...args, '--metadata-json', JSON.stringify(metadata)])).toMatchObject({
    metadata,
  });
  expect(parseCliArguments(args)).not.toHaveProperty('metadata');
  expect(() => parseCliArguments([...args, '--metadata-json', '{'])).toThrow(/JSON object/u);
  expect(() =>
    parseCliArguments([...args, '--metadata-json', '{"unsandboxed":"not-needed"}']),
  ).toThrow(/Unknown bundle metadata/u);
  expect(() =>
    parseCliArguments([...args, '--metadata-json', '{}', '--metadata-json', '{}']),
  ).toThrow(/only.*once/u);
});

test('uses the same presentation header for module bundles and keeps the computed requirement', async () => {
  const f = await syntheticModuleProject('required');
  try {
    Object.assign(f.manifest.extensionBundles[0], {metadata});
    await f.save();
    const built = await createDeterministicSb3(f.sourceDirectory);
    const header = topHeader(built.bundlePlans[0].contents);
    expect(header).toContain(
      '// By: Application Author\n// Author URL: http://example.com/author\n',
    );
    expect(header).toContain('// Package: @example/application\n');
    expect(header).toContain('// Unsandboxed: required\n');
    const project = JSON.parse(strFromU8(unzipSync(built.archive)['project.json']));
    const encoded = project.extensionURLs.projectbundle as string;
    expect(topHeader(Buffer.from(encoded.slice(encoded.indexOf(',') + 1), 'base64'))).toBe(header);
  } finally {
    await f.cleanup();
  }
});
